#!/usr/bin/env python3
"""Generate an OPM Flow twin of the compact NVRS SPE10 benchmark deck."""
import math
import os
import sys

import numpy as np

from make_decks import corey_swof, fmt_array
from make_spe10 import DX, DY, DZ, NCELL, NX, NY, NZ, load_spe10


def well_index(k_md):
    return 2.0 * math.pi * 1.127e-3 * k_md * DZ / math.log((0.2 * DX) / 1.0)


def write(path):
    """Write the matched two-phase Eclipse deck to path."""
    kx, kz, phi = load_spe10()
    phi = np.maximum(phi, 1.0e-4)
    swof = corey_swof(dict(swi=0.2, swr=0.2))

    lines = []
    add = lines.append
    add("-- Generated by benchmark/make_spe10_opm.py")
    add("-- OPM Flow twin of benchmark/runs/SPE10/SPE10.DATA")
    add("")
    add("RUNSPEC")
    add("TITLE")
    add(" SPE10 MATCHED TWO-PHASE NVRS TWIN")
    add("DIMENS")
    add(" %d %d %d /" % (NX, NY, NZ))
    add("OIL")
    add("WATER")
    add("FIELD")
    add("TABDIMS")
    add(" 1 1 %d 60 /" % (len(swof) + 20))
    add("WELLDIMS")
    add(" 5 %d 4 5 /" % (5 * NZ))
    add("START")
    add(" 1 'JAN' 2020 /")
    add("UNIFIN")
    add("UNIFOUT")
    add("")
    add("GRID")
    add("INIT")
    for keyword, value in (("DX", DX), ("DY", DY), ("DZ", DZ)):
        add(keyword)
        add(" %d*%g /" % (NCELL, value))
    add("TOPS")
    add(" %d*0 /" % (NX * NY))
    add("PERMX")
    add(fmt_array(kx))
    add("/")
    add("COPY")
    add(" 'PERMX' 'PERMY' /")
    add("/")
    add("PERMZ")
    add(fmt_array(kz))
    add("/")
    add("PORO")
    add(fmt_array(phi))
    add("/")
    add("")
    add("PROPS")
    add("PVTW")
    add(" 6000 1.01 0.0 0.3 0.0 /")
    add("PVCDO")
    add(" 6000 1.01 0.0 3.0 0.0 /")
    # Flow CPR needs a nonzero pressure accumulation derivative. At this value
    # the pore-volume change over 2000 psi is 0.8 percent.
    add("ROCK")
    add(" 6000 4.0e-6 /")
    add("DENSITY")
    # Flow uses rho_surface/B; NVRS uses 64 and 53 lb/ft3 directly.
    add(" 53.53 64.64 0.0624 /")
    add("SWOF")
    for sw, kro, krw in swof:
        add(" %.8g %.8g %.8g 0" % (sw, krw, kro))
    add("/")
    add("")
    add("SOLUTION")
    add("PRESSURE")
    add(" %d*6000 /" % NCELL)
    add("SWAT")
    add(" %d*0.2 /" % NCELL)
    add("RPTRST")
    add(" 'BASIC=2' /")
    add("")
    add("SUMMARY")
    for keyword in ("WOPR", "WWPR", "WWCT", "WBHP"):
        add(keyword)
        for name in ("P1", "P2", "P3", "P4"):
            add(" '%s'" % name)
        if keyword == "WBHP":
            add(" 'INJ'")
        add("/")
    add("WWIR")
    add(" 'INJ' /")
    for keyword in ("FOPR", "FWPR", "FOPT", "FWPT", "FPR", "TCPU"):
        add(keyword)
    add("")
    add("SCHEDULE")
    add("TUNING")
    add(" 1 100 /")
    add(" /")
    add(" /")
    add("WELSPECS")
    add(" 'INJ' 'INJ' 30 110 1 'WATER' /")
    for name, i, j in (("P1", 1, 1), ("P2", 60, 1),
                       ("P3", 60, 220), ("P4", 1, 220)):
        add(" '%s' 'PRO' %d %d 1 'OIL' /" % (name, i, j))
    add("/")
    add("COMPDAT")
    wells = (("INJ", 30, 110), ("P1", 1, 1), ("P2", 60, 1),
             ("P3", 60, 220), ("P4", 1, 220))
    for name, i, j in wells:
        for k in range(1, NZ + 1):
            cell = (i - 1) + NX * ((j - 1) + NY * (k - 1))
            add(" '%s' %d %d %d %d 'OPEN' 1* %.10g 2.0 1* 0 1* 'Z' /" %
                (name, i, j, k, k, well_index(kx[cell])))
    add("/")
    add("WCONINJE")
    add(" 'INJ' 'WATER' 'OPEN' 'RATE' 5000 1* 10000 /")
    add("/")
    add("WCONPROD")
    for name in ("P1", "P2", "P3", "P4"):
        add(" '%s' 'OPEN' 'BHP' 5* 4000 /" % name)
    add("/")
    add("TSTEP")
    add(" 20*100 /")
    add("END")

    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")
    print("[spe10-opm] wrote %s (%.1f MB)" %
          (path, os.path.getsize(path) / 1.0e6))
    print("[spe10-opm] porosity %.6g .. %.6g; %d values at floor" %
          (phi.min(), phi.max(), int(np.count_nonzero(phi == 1.0e-4))))


if __name__ == "__main__":
    target = (sys.argv[1] if len(sys.argv) > 1 else
              os.path.join(os.path.dirname(__file__), "runs", "SPE10",
                           "SPE10_OPM.DATA"))
    write(target)
